-- CineVaals: catálogo independente do cronograma semanal
-- Execute este arquivo no SQL Editor do projeto Supabase antes de usar o catálogo.

create table if not exists public.catalog (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null check (category in ('Filme', 'Série', 'Animação', 'Dorama', 'Anime')),
  status text not null default 'Está na Fila'
    check (status in ('Já Assistido', 'Está no Cronograma', 'Está na Fila')),
  image text,
  description text,
  created_at timestamptz not null default now(),
  sort_order integer not null default 0
);

alter table public.catalog enable row level security;

-- O catálogo pode ser consultado publicamente no site.
drop policy if exists "Public can read catalog" on public.catalog;
create policy "Public can read catalog"
  on public.catalog for select
  to anon, authenticated
  using (true);

-- Somente administradores autorizados podem cadastrar, editar ou remover títulos.
drop policy if exists "Admins can insert catalog" on public.catalog;
create policy "Admins can insert catalog"
  on public.catalog for insert
  to authenticated
  with check (public.is_cinevaals_admin());

drop policy if exists "Admins can update catalog" on public.catalog;
create policy "Admins can update catalog"
  on public.catalog for update
  to authenticated
  using (public.is_cinevaals_admin())
  with check (public.is_cinevaals_admin());

drop policy if exists "Admins can delete catalog" on public.catalog;
create policy "Admins can delete catalog"
  on public.catalog for delete
  to authenticated
  using (public.is_cinevaals_admin());

grant select on public.catalog to anon, authenticated;
grant insert, update, delete on public.catalog to authenticated;
grant usage, select on sequence public.catalog_id_seq to authenticated;


-- Temporada opcional para séries, animações, doramas e animes.
alter table public.catalog add column if not exists season text;
